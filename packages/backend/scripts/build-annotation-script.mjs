import * as esbuild from "esbuild";
import { mkdirSync, readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";
import { spawnSync } from "child_process";

const __dirname = dirname(fileURLToPath(import.meta.url));
const backendRoot = join(__dirname, "..");
const entry = join(backendRoot, "preview-annotation-src/index.ts");
const outJs = join(backendRoot, "preview-annotation-src/.build/bundle.js");
const outTs = join(
  backendRoot,
  "convex/_sandbox_runtime/previewAnnotationScript.generated.ts",
);
const annotationTsconfig = join(
  backendRoot,
  "preview-annotation-src/tsconfig.json",
);

const typecheck = spawnSync(
  process.platform === "win32" ? "npx.cmd" : "npx",
  ["tsc", "--noEmit", "-p", annotationTsconfig],
  { cwd: backendRoot, encoding: "utf8", shell: process.platform === "win32" },
);
if (typecheck.status !== 0) {
  if (typecheck.stdout) process.stderr.write(typecheck.stdout);
  if (typecheck.stderr) process.stderr.write(typecheck.stderr);
  console.error("preview-annotation-src typecheck failed; refusing to bundle");
  process.exit(typecheck.status ?? 1);
}

mkdirSync(dirname(outJs), { recursive: true });

await esbuild.build({
  entryPoints: [entry],
  bundle: true,
  platform: "browser",
  // Runs in the previewed app's browser, so no downlevelling helpers are needed
  // and names stay as authored (see keepNames note below).
  target: "es2020",
  format: "iife",
  // keepNames/minifyIdentifiers would emit calls to a module-scope `__name`
  // helper. Harmless here (the whole bundle ships together) but the point of
  // this build step is an injected script with zero external references.
  keepNames: false,
  minify: false,
  outfile: outJs,
  logLevel: "info",
});

const bundled = readFileSync(outJs, "utf8").trim();

const helper = bundled.match(/\b(__name|__defProp|__spreadValues|__async)\b/);
if (helper) {
  console.error(
    `Bundle references esbuild helper ${helper[1]}; the injected script must be self-contained`,
  );
  process.exit(1);
}
if (!bundled.includes("eva-preview-annotate-ready")) {
  console.error("Bundle is missing the annotation protocol; refusing to write");
  process.exit(1);
}

const escaped = bundled
  .replace(/\\/g, "\\\\")
  .replace(/`/g, "\\`")
  .replace(/\$/g, "\\$");

writeFileSync(
  outTs,
  `"use node";\n\n/**\n * GENERATED by scripts/build-annotation-script.mjs — do not edit.\n * Source: preview-annotation-src/index.ts\n */\nexport const PREVIEW_ANNOTATION_SCRIPT = \`${escaped}\`.trim();\n`,
  "utf8",
);

console.log("Wrote", outTs, "(" + bundled.length, "bytes bundled)");
