/** SVG markup for a provider icon — used by contenteditable `innerHTML` chips. */
export function linkProviderIconHtml(provider: LinkProvider): string {
  const mark = PROVIDER_MARKS[provider];
  return `<svg viewBox="${mark.viewBox}" fill="currentColor" aria-hidden="true" class="${mark.className}">${mark.body}</svg>`;
}

/** Brand icon for a link-chip provider, sized to sit inside a chip. */
export function LinkProviderIcon({ provider }: { provider: LinkProvider }) {
  const mark = PROVIDER_MARKS[provider];
  return (
    <svg
      viewBox={mark.viewBox}
      fill="currentColor"
      aria-hidden="true"
      className={mark.className}
      dangerouslySetInnerHTML={{ __html: mark.body }}
    />
  );
}
